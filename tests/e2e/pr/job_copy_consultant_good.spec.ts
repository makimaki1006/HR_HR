import { expect, test } from '@playwright/test';
import { login } from './helpers/login';
import { detailFixture, goodFixture, goodRow, scopeFixture } from '../../../frontend/src/screens/job-copy/consultantRisk.testFixtures';

test('いい案件の印・共通の詳細・メモ追記・担当とURLの保持', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/job-copy/consultant-scope?*', route => route.fulfill({ json: { ...scopeFixture, owner: new URL(route.request().url()).searchParams.get('owner') ?? '11' } }));
  await page.route('**/api/job-copy/consultant-good?*', route => route.fulfill({ json: { ...goodFixture, rows: new URL(route.request().url()).searchParams.get('owner') === '22' ? [] : goodFixture.rows } }));
  await page.route('**/api/consulting/deal-detail?*', route => route.fulfill({ json: detailFixture }));
  await page.route('**/api/job-copy/listings?*', route => route.fulfill({ json: { status: 'ready', total: 1, next_offset: null, listings: [{ id: '501' }] } }));
  let memo = '10/16 求人の見直しを提案';
  await page.route('**/api/crm/workspace/deals/101?*', route => route.fulfill({ json: { hubspot_portal_id: '123', selected: { deal: { teian: memo, actionyotei: '2026-10-21', actionnaiyou: 'call' } }, partial: [] } }));
  await page.route('**/api/crm/edit-schema?*', route => route.fulfill({ json: { writes_enabled: true, editable: [{ object: 'deal', name: 'teian', type: 'string' }, { object: 'deal', name: 'actionyotei', type: 'date' }, { object: 'deal', name: 'actionnaiyou', type: 'enumeration', options: [{ value: 'call', label: '電話' }] }] } }));
  const patches: { base: { teian: string }; set: { teian: string }; operation_id: string }[] = [];
  await page.route('**/api/crm/deals/101', route => {
    const body = route.request().postDataJSON() as typeof patches[number]; patches.push(body); memo = body.set.teian;
    return route.fulfill({ json: { status: 'saved', operation_id: body.operation_id, values: body.set, objects_values: {} } });
  });
  await login(page);
  await page.goto('/app/job-copy?view=good&owner=11&owner_field=consultant');
  const list = page.getByRole('region', { name: 'いい案件の一覧' });
  await expect(page.getByRole('heading', { level: 1, name: /^いい案件/ })).toHaveText('いい案件 3件');
  await expect(list.getByRole('heading', { level: 2 })).toHaveCount(0);
  await expect(list.getByRole('columnheader', { name: '理由', exact: true })).toBeVisible();
  await expect(list.getByText('MTG：採用を継続し、次の募集職種を増やす方向で相談する', { exact: true })).toBeVisible();
  const row = list.getByRole('row').filter({ has: page.getByRole('button', { name: goodRow.name }) });
  await expect(row.getByRole('listitem')).toHaveText((goodRow.good_flags ?? []).map(f => f.label));
  await expect(row.getByText('危ない名札もあり（2件）')).toBeVisible();
  await expect(page.getByText('今日わかった', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'いい案件', exact: true })).toHaveAttribute('aria-current', 'page');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const dir = process.env.CONSULTANT_SCREENSHOT_DIR;
  if (dir) await page.screenshot({ path: `${dir}/good-list.png`, fullPage: false });
  await row.getByRole('button').click();
  const detail = page.getByRole('dialog');
  await expect(detail.getByRole('button', { name: '終わった → 次の予定' })).toBeVisible();
  await expect(detail.getByText('MTG：採用を継続し、次の募集職種を増やす方向で相談する', { exact: true })).toBeVisible();
  await expect(detail.getByText('10/16 求人の見直しを提案', { exact: true })).toBeVisible();
  const draft = detail.getByLabel('追記するメモ');
  await draft.fill('募集職種を増やす提案をした。\n来週の打ち合わせで内容を決める。');
  expect(await detail.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  if (dir) await page.screenshot({ path: `${dir}/good-detail-memo.png`, fullPage: false });
  await detail.getByRole('button', { name: 'メモを保存' }).click();
  await expect(detail.getByText('保存済み', { exact: true })).toHaveClass('nt-green');
  expect(patches).toHaveLength(1);
  expect(patches[0]?.base).toEqual({ teian: '10/16 求人の見直しを提案' });
  expect(patches[0]?.set.teian).toMatch(/^10\/16 求人の見直しを提案 \/ \d{2}\/\d{2} 募集職種を増やす提案をした。 来週の打ち合わせで内容を決める。$/);
  await expect(draft).toHaveValue('');
  await detail.getByRole('button', { name: '閉じる', exact: true }).click();
  await page.getByRole('combobox', { name: '担当者', exact: true }).selectOption('22');
  await expect(list.getByText('該当する案件はありません。')).toBeVisible();
  await expect(page.getByRole('heading', { level: 1, name: /^いい案件/ })).toHaveText('いい案件 0件');
  await page.reload(); await expect(list.getByText('該当する案件はありません。')).toBeVisible();
  await expect(page).toHaveURL(/view=good/); await expect(page).toHaveURL(/owner=22/);
  await page.getByRole('button', { name: '案件一覧', exact: true }).click(); await expect(page).toHaveURL(/view=deals/);
  await page.goBack(); await expect(list).toBeVisible();
  await expect(page.getByRole('combobox', { name: '担当者', exact: true })).toHaveValue('22');
  expect(errors).toEqual([]);
});
